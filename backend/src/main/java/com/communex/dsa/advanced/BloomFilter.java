package com.communex.dsa.advanced;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.BitSet;

/**
 * Space-efficient probabilistic membership filter.
 *
 * False positives are possible, but false negatives are not expected
 * for values that have been added, provided the filter is not modified
 * externally or cleared.
 */
public final class BloomFilter {

    private final BitSet bits;
    private final int bitSize;
    private final int hashCount;

    // Initialize the Bloom filter
    public BloomFilter(int bitSize, int hashCount) {

        if (bitSize < 1 || hashCount < 1) {
            throw new IllegalArgumentException(
                    "Sizes must be positive"
            );
        }

        this.bitSize = bitSize;
        this.hashCount = hashCount;
        this.bits = new BitSet(bitSize);
    }

    /**
     * Adds a value to the Bloom filter.
     *
     * @param value value to add
     */
    public void add(String value) {

        if (value == null) {
            throw new IllegalArgumentException(
                    "Value required"
            );
        }

        // Set each bit generated by the hash functions
        for (int i = 0; i < hashCount; i++) {
            int bitIndex = index(value, i);
            bits.set(bitIndex);
        }
    }

    /**
     * Checks whether a value might exist in the filter.
     *
     * @param value value to check
     * @return false if definitely absent; true if possibly present
     */
    public boolean mightContain(String value) {

        if (value == null) {
            throw new IllegalArgumentException(
                    "Value required"
            );
        }

        // Every corresponding bit must be set
        for (int i = 0; i < hashCount; i++) {

            int bitIndex = index(value, i);

            if (!bits.get(bitIndex)) {
                return false;
            }
        }

        return true;
    }

    /**
     * Generates a bit index using SHA-256 and a seed.
     *
     * @param value value to hash
     * @param seed hash-function seed
     * @return valid index within the configured bit range
     */
    private int index(String value, int seed) {

        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");

            // Include the seed to derive different hash positions
            digest.update((byte) seed);

            byte[] hash = digest.digest(
                    value.getBytes(StandardCharsets.UTF_8)
            );

            // Build an unsigned value from the first eight hash bytes
            long number = 0;

            for (int i = 0; i < 8; i++) {
                number = (number << 8) | (hash[i] & 0xffL);
            }

            // Convert the hash value into a valid BitSet index
            return (int) Long.remainderUnsigned(number, bitSize);

        } catch (NoSuchAlgorithmException exception) {
            throw new IllegalStateException(
                    "SHA-256 unavailable",
                    exception
            );
        }
    }
}